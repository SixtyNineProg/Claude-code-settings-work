def main() -> int:
    written = 0
    for (eval_dir, config), rows in GRADES.items():
        expectations = [
            {"text": text, "passed": passed, "evidence": evidence}
            for text, passed, evidence in rows
        ]
        passed = sum(1 for row in expectations if row["passed"])
        total = len(expectations)

        payload = {
            "expectations": expectations,
            "summary": {
                "passed": passed,
                "failed": total - passed,
                "total": total,
                "pass_rate": round(passed / total, 4),
            },
        }

        run_dir = ROOT / eval_dir / config / "run-1"
        metrics_path = run_dir / "outputs" / "metrics.json"
        timing_path = run_dir / "timing.json"
        if metrics_path.exists():
            payload["execution_metrics"] = json.loads(
                metrics_path.read_text(encoding="utf-8")
            )
        if timing_path.exists():
            payload["timing"] = {
                "executor_duration_seconds": json.loads(
                    timing_path.read_text(encoding="utf-8")
                ).get("total_duration_seconds"),
            }
        payload["eval_feedback"] = FEEDBACK.get(eval_dir, "")

        target = run_dir / "grading.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        written += 1
        print(f"{eval_dir}/{config}: {passed}/{total}")

    print(f"\nфайлов записано: {written}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
